"""Module 10 — Capital employed & reinvestment (Capital Investment Bridge).

Where did the year's capital go, and what funded it. Built entirely from
Module 3/4/6 outputs; the frontend only renders.

Investment side (the bridge, waterfall-ready like cash_bridge_annual):
    NOA_begin + Σ signed group deltas = NOA_end
Component groups reuse the Module 8 concept sets, restricted to the
operating effective_class; each side carries an "other" residual group
(OA/OL remainder) so the sum is EXACT by construction — undisclosed or
unmapped components land in the residual, never force the identity.
Liability groups enter with a minus sign (growing supplier credit or
customer advances reduces NOA).

Funding side (identity from NOA = CSE + MI + NFO, Module 3 exact):
    ΔNOA = ΔCSE + ΔMI + ΔNFO
reported as summary columns and check B3.

Reinvestment metrics (guards as in Module 4 — never a misleading ratio):
- reinvestment_rate = ΔNOA / OI_after_tax (share of operating income
  reinvested in net operating assets)
- noa_growth vs revenue_growth (capital productivity direction; a NOA
  growth persistently above revenue growth is the falling-ATO story)
- capex_paid vs D&A (sum of the disclosed supp_* depreciation/amortization
  lines); capex/D&A ratio. Maintenance-vs-growth capex split is NOT
  knowable from statements — carried as a note, never estimated.
- fcf_from_oi = OI_after_tax − ΔNOA (Penman: free cash flow generated by
  operations). Its difference vs the cash-statement fcf_simple is REPORTED
  as fcf_articulation_diff — CAS interest classification, items bypassing
  operating income (FX, dirty surplus, M&A) and measurement differences
  make it nonzero; informational, never forced.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from .economics_map import (CUSTOMER_ADVANCES, INTANGIBLES_GROUP, INVENTORY,
                            PPE_GROUP, RECEIVABLES_PREPAY, SUPPLIER_CREDIT)
from .ratios import NEAR_ZERO_FRAC
from .store import Store

# (group_id, label, concept set) — ids match Module 8 node ids.
ASSET_GROUPS = [
    ("inventory", "Δ Inventory", INVENTORY),
    ("receivables_prepaid", "Δ Receivables & prepayments", RECEIVABLES_PREPAY),
    ("ppe_cip", "Δ PP&E & construction", PPE_GROUP),
    ("intangibles_other_lt", "Δ Intangibles & other LT", INTANGIBLES_GROUP),
]
LIABILITY_GROUPS = [
    ("supplier_credit", "Δ Supplier credit (−)", SUPPLIER_CREDIT),
    ("customer_advances", "Δ Customer advances (−)", CUSTOMER_ADVANCES),
]
OTHER_OA_LABEL = "Δ Other operating assets"
OTHER_OL_LABEL = "Δ Other operating liabilities (−)"

DA_CONCEPTS = ["supp_depreciation", "supp_rou_asset_depreciation",
               "supp_intangible_amortization", "supp_lt_deferred_amortization"]

FCF_FROM_OI_DEF = ("OI after tax − ΔNOA (Penman: free cash flow generated by "
                   "operations; reformulation identity C − I = OI − ΔNOA)")
ARTICULATION_NOTE = ("fcf_from_oi − fcf_simple. Nonzero is expected: CAS puts "
                     "interest received in investing and interest paid in "
                     "financing; FX translation, dirty-surplus equity items "
                     "and M&A move NOA without passing through OI; capex cash "
                     "timing differs from accruals. Reported, never forced.")
CAPEX_SPLIT_NOTE = ("Maintenance-vs-growth capex split is NOT knowable from "
                    "financial statements; any split is an assumption.")


def _group_balances(comp_year: pd.DataFrame, oa: float, ol: float) -> dict:
    """Group balances for one year; residual groups make sums exact to OA/OL."""
    g: dict[str, float] = {}
    ca = comp_year[comp_year.effective_class == "operating_asset"]
    known = 0.0
    for gid, _, concepts in ASSET_GROUPS:
        v = float(ca[ca.concept.isin(concepts)].value.sum())  # 0 if none
        g[gid] = v
        known += v
    g["other_operating_assets"] = oa - known
    cl = comp_year[comp_year.effective_class == "operating_liability"]
    known = 0.0
    for gid, _, concepts in LIABILITY_GROUPS:
        v = float(cl[cl.concept.isin(concepts)].value.sum())
        g[gid] = v
        known += v
    g["other_operating_liabilities"] = ol - known
    return g


def compute_capital_bridge(
    bs: pd.DataFrame, is_: pd.DataFrame, comp: pd.DataFrame,
    cf_facts: pd.DataFrame, cash_summary: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Inputs: Module-3 outputs + cashflow std_facts + Module-6 summary for
    one company. Returns (bridge_long, summary_wide, checks), annual."""
    bs = bs[bs.end_date.str.endswith("1231")].sort_values("end_date")
    isa = is_[(is_.period_kind == "cumulative")
              & is_.end_date.str.endswith("1231")]
    comp = comp[comp.end_date.str.endswith("1231")]
    cf = cf_facts[
        (cf_facts.statement == "cashflow") & (cf_facts.report_type == "1")
        & (cf_facts.period_kind == "cumulative")
        & (cf_facts.value_type == "reported")
        & cf_facts.end_date.str.endswith("1231")
    ]

    bs_by_year = {r.end_date[:4]: r for r in bs.itertuples()}
    is_by_year = {r.end_date[:4]: r for r in isa.itertuples()}
    cf_by_year = {y: dict(zip(g.concept, g.value))
                  for y, g in cf.groupby(cf.end_date.str[:4])}
    fcf_by_year = {r.end_date[:4]: r.fcf_simple
                   for r in cash_summary.itertuples()} if not cash_summary.empty else {}

    bridge_rows, summary_rows, check_rows = [], [], []
    for year in sorted(bs_by_year):
        cur = bs_by_year[year]
        prev = bs_by_year.get(str(int(year) - 1))
        ts, ed = cur.ts_code, cur.end_date
        r = is_by_year.get(year)
        rp = is_by_year.get(str(int(year) - 1))
        cfy = cf_by_year.get(year, {})
        flags = []

        rev = r.total_revenue if r is not None else np.nan
        oi = r.oi_after_tax if r is not None else np.nan
        capex = cfy.get("capex_paid", np.nan)
        da_vals = [cfy.get(c) for c in DA_CONCEPTS]
        da_vals = [v for v in da_vals if v is not None and not pd.isna(v)]
        if da_vals:
            da_total = float(sum(da_vals))
        else:
            da_total = np.nan
            flags.append("da_not_disclosed")
        capex_to_da = (capex / da_total
                       if not pd.isna(capex) and not pd.isna(da_total)
                       and da_total != 0 else np.nan)

        if prev is None:
            flags.append("no_opening_balance")
            summary_rows.append(dict(
                ts_code=ts, end_date=ed,
                noa_begin=np.nan, noa_end=cur.noa, delta_noa=np.nan,
                delta_cse=np.nan, delta_mi=np.nan, delta_nfo=np.nan,
                revenue=rev, revenue_growth=np.nan, noa_growth=np.nan,
                oi_after_tax=oi, reinvestment_rate=np.nan,
                capex_paid=capex, da_total=da_total, capex_to_da=capex_to_da,
                fcf_from_oi=np.nan, fcf_simple=fcf_by_year.get(year, np.nan),
                fcf_articulation_diff=np.nan,
                fcf_from_oi_def=FCF_FROM_OI_DEF,
                articulation_note=ARTICULATION_NOTE,
                capex_split_note=CAPEX_SPLIT_NOTE,
                cap_flags=",".join(flags)))
            continue

        gp = _group_balances(comp[comp.end_date == prev.end_date],
                             prev.oa, prev.ol)
        gc = _group_balances(comp[comp.end_date == ed], cur.oa, cur.ol)

        order = 0
        bridge_rows.append(dict(
            ts_code=ts, end_date=ed, step_order=order, concept="noa_begin",
            label=f"NOA, end {int(year) - 1}", value=prev.noa,
            step_kind="start"))
        total = prev.noa
        for gid, label, _ in ASSET_GROUPS:
            order += 1
            v = gc[gid] - gp[gid]
            bridge_rows.append(dict(ts_code=ts, end_date=ed, step_order=order,
                                    concept=gid, label=label, value=v,
                                    step_kind="adjustment"))
            total += v
        order += 1
        v = gc["other_operating_assets"] - gp["other_operating_assets"]
        bridge_rows.append(dict(ts_code=ts, end_date=ed, step_order=order,
                                concept="other_operating_assets",
                                label=OTHER_OA_LABEL, value=v,
                                step_kind="adjustment"))
        total += v
        for gid, label, _ in LIABILITY_GROUPS:
            order += 1
            v = -(gc[gid] - gp[gid])
            bridge_rows.append(dict(ts_code=ts, end_date=ed, step_order=order,
                                    concept=gid, label=label, value=v,
                                    step_kind="adjustment"))
            total += v
        order += 1
        v = -(gc["other_operating_liabilities"]
              - gp["other_operating_liabilities"])
        bridge_rows.append(dict(ts_code=ts, end_date=ed, step_order=order,
                                concept="other_operating_liabilities",
                                label=OTHER_OL_LABEL, value=v,
                                step_kind="adjustment"))
        total += v
        order += 1
        bridge_rows.append(dict(ts_code=ts, end_date=ed, step_order=order,
                                concept="noa_end", label=f"NOA, end {year}",
                                value=cur.noa, step_kind="total"))

        delta_noa = cur.noa - prev.noa
        delta_cse = cur.cse_calc - prev.cse_calc
        delta_mi = cur.minority_interests - prev.minority_interests
        delta_nfo = cur.nfo - prev.nfo

        check_rows += [
            dict(ts_code=ts, end_date=ed, check="B1_bridge_additive",
                 residual=total - cur.noa),
            dict(ts_code=ts, end_date=ed, check="B2_delta_noa_vs_oa_ol",
                 residual=delta_noa - ((cur.oa - prev.oa) - (cur.ol - prev.ol))),
            dict(ts_code=ts, end_date=ed, check="B3_funding_identity",
                 residual=delta_noa - (delta_cse + delta_mi + delta_nfo)),
        ]

        floor = NEAR_ZERO_FRAC * abs(rev) if not pd.isna(rev) else np.inf
        if pd.isna(rev):
            flags.append("no_income_statement")

        rev_prev = rp.total_revenue if rp is not None else np.nan
        if pd.isna(rev_prev) or abs(rev_prev) < 1.0:
            revenue_growth = np.nan
            flags.append("no_prior_revenue")
        else:
            revenue_growth = rev / rev_prev - 1.0

        if abs(prev.noa) < floor:
            noa_growth = np.nan
            flags.append("noa_base_near_zero_suppressed")
        elif prev.noa < 0:
            noa_growth = np.nan
            flags.append("negative_noa_base")
        else:
            noa_growth = delta_noa / prev.noa

        if pd.isna(oi) or abs(oi) < floor:
            reinvestment_rate = np.nan
            if not pd.isna(oi):
                flags.append("oi_near_zero_suppressed")
        else:
            reinvestment_rate = delta_noa / oi

        fcf_from_oi = oi - delta_noa if not pd.isna(oi) else np.nan
        fcf_simple = fcf_by_year.get(year, np.nan)
        art_diff = (fcf_from_oi - fcf_simple
                    if not pd.isna(fcf_from_oi) and not pd.isna(fcf_simple)
                    else np.nan)

        summary_rows.append(dict(
            ts_code=ts, end_date=ed,
            noa_begin=prev.noa, noa_end=cur.noa, delta_noa=delta_noa,
            delta_cse=delta_cse, delta_mi=delta_mi, delta_nfo=delta_nfo,
            revenue=rev, revenue_growth=revenue_growth, noa_growth=noa_growth,
            oi_after_tax=oi, reinvestment_rate=reinvestment_rate,
            capex_paid=capex, da_total=da_total, capex_to_da=capex_to_da,
            fcf_from_oi=fcf_from_oi, fcf_simple=fcf_simple,
            fcf_articulation_diff=art_diff,
            fcf_from_oi_def=FCF_FROM_OI_DEF,
            articulation_note=ARTICULATION_NOTE,
            capex_split_note=CAPEX_SPLIT_NOTE,
            cap_flags=",".join(flags)))

    bridge = pd.DataFrame(
        bridge_rows, columns=["ts_code", "end_date", "step_order", "concept",
                              "label", "value", "step_kind"])
    summary = pd.DataFrame(summary_rows).sort_values("end_date").reset_index(drop=True)
    checks = pd.DataFrame(
        check_rows, columns=["ts_code", "end_date", "check", "residual"])
    return bridge, summary, checks


def build_capital_bridge(store: Store, ts_code: str) -> dict:
    bs = store.con.execute(
        "SELECT * FROM reformulated_bs WHERE ts_code = ?", [ts_code]).df()
    is_ = store.con.execute(
        "SELECT * FROM reformulated_is WHERE ts_code = ?", [ts_code]).df()
    comp = store.con.execute(
        "SELECT * FROM reformulated_bs_components WHERE ts_code = ?",
        [ts_code]).df()
    cf_facts = store.con.execute(
        "SELECT * FROM std_facts WHERE ts_code = ? AND statement='cashflow'",
        [ts_code]).df()
    cash_summary = store.con.execute(
        "SELECT * FROM cash_summary_annual WHERE ts_code = ?", [ts_code]).df()
    if bs.empty or is_.empty:
        raise RuntimeError(
            f"No reformulated data for {ts_code}; run `reformulate` first.")
    bridge, summary, checks = compute_capital_bridge(
        bs, is_, comp, cf_facts, cash_summary)
    for table, df in [("capital_bridge_annual", bridge),
                      ("capital_summary_annual", summary),
                      ("capital_bridge_checks", checks)]:
        store.con.register("_df", df)
        exists = store.con.execute(
            "SELECT count(*) FROM information_schema.tables WHERE table_name=?",
            [table]).fetchall()[0][0]
        if exists:
            store.con.execute(f"DELETE FROM {table} WHERE ts_code = ?", [ts_code])
            store.con.execute(f"INSERT INTO {table} BY NAME SELECT * FROM _df")
        else:
            store.con.execute(f"CREATE TABLE {table} AS SELECT * FROM _df")
        store.con.unregister("_df")
    return {"bridge": bridge, "summary": summary, "checks": checks}
